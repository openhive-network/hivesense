#!/usr/bin/env bash
# The step functions are called indirectly, through `step`.
# shellcheck disable=SC2317,SC2329
# The checks AIDEV's verification slots run (.aidev/project.yaml), as one junit
# report per suite: each named step is a test case, its log the failure body.
#
#   .aidev/run-checks.sh <suite> <step>...
#
#   - shellcheck      ShellCheck at warning severity on every *.sh (the files CI's
#                     lint_bash_scripts checks), at default severity on .aidev/'s own
#   - sqlfluff        `sqlfluff lint` with the repository's .sqlfluff (CI's
#                     lint_sql_scripts, which fails on any violation)
#   - unit            tests/unit with python's unittest (no database, no network)
#   - sql-registered  every .sql file under db/ and endpoints/ is applied by
#                     scripts/install_app.sh (a file it misses never reaches a database)
#   - stack-pins      the four upstream images of .aidev/test-stack.compose.yml are
#                     pinned as repo:tag@sha256 for .gitlab-ci.yml's UPSTREAM_BRANCH
#   - install         scripts/install_app.sh into the stack's HAF database
#                     (HIVESENSE_TEST_DB_HOST, default `haf`), which already has
#                     hivemind installed, through install_with_app_lock.py (its log
#                     must not carry the wrapper-not-found WARNING); then the block
#                     processor's start-up identity (init_local_sync_identity) and
#                     tests/test_sync_chains.sql
#   - events-id       CI's events_id_test (#54): seed hafd.contexts.events_id = 0
#                     for hivesense_app, run scripts/sync_embeddings.py's
#                     ensure_context_detached, expect hive.unreachable_event_id()
#   - install-lock    CI's lock_skip_test: while another session holds the app's
#                     shared install lock, install_app.sh skips, exits 0 and leaves
#                     the installed schema as it was
#   - reinstall       scripts/uninstall_app.sh, then install again
#   - embed-search    reinstall configured as CI's sync job (all-minilm:l6-v2, 384
#                     dims, the stack's `ollama`; token threshold 200), seed
#                     .aidev/seed_posts.sql, embed the seeded posts with
#                     generate_embeddings_for_posts, check what posts_vectors
#                     holds, build the HNSW index and check it exists, check the
#                     paging search find_nearest_posts_with_embedding against the
#                     one-shot one, then the embedding-backed calls of
#                     .aidev/hivesense_smoke.py (one junit case per call); finally
#                     reinstall as `install` does, so the steps after it see that state
#   - embed-slice     embed-search in CI's slice configuration
#                     (mxbai-embed-xsmall-v1, Matryoshka slice to 256 dims)
#   - embed-pca       embed-search's embedding in PCA mode, with a projection
#                     matrix generated by the step: reduced vectors and search
#   - api-smoke       PostgREST over the installed schema, the calls in
#                     .aidev/hivesense_smoke.py; one junit case per call
#
# The steps from install on need the HAF stack (.aidev/test-stack.compose.yml).
# Reports go to test-results/<suite>/: junit.xml (one case per step) plus one
# <check set>.xml per .aidev/hivesense_smoke.py run.
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

suite="${1:?usage: $0 <suite> <step>...}"; shift
out="test-results/$suite"
rm -rf "$out"; mkdir -p "$out"
cases="$out/cases.tsv"; : > "$cases"

DB_HOST="${HIVESENSE_TEST_DB_HOST:-haf}"
ADMIN_URL="postgresql://haf_admin@$DB_HOST/haf_block_log"
export HIVESENSE_TEST_USER_URL="postgresql://hivesense_user@$DB_HOST/haf_block_log"

status=0
# record CASES_FILE NAME RC SECONDS LOG
record() {
    if [ "$3" -eq 0 ]; then
        printf 'case\t%s\tpass\t%s\t\n' "$2" "$4" >> "$1"
    else
        printf 'case\t%s\tfail\t%s\texit %s\t%s\n' "$2" "$4" "$3" "$5" >> "$1"
    fi
}

step() {
    local name="$1"; shift
    local log="$out/$name.log" t0=$SECONDS rc=0
    echo "== $name" >&2
    "$@" > "$log" 2>&1 < /dev/null || rc=$?
    [ "$rc" -eq 0 ] || { status=1; tail -40 "$log" >&2; }
    record "$cases" "$name" "$rc" "$((SECONDS - t0))" "$log"
}

run_shellcheck() {
    shellcheck --version | head -2
    # The project's scripts carry notes (SC2015) today; warnings are the floor.
    find . -name .git -prune -o -name .aidev -prune -o -name test-results -prune -o -type f -name '*.sh' -print0 \
        | xargs -0 shellcheck -S warning -f gcc || return 1
    shellcheck -f gcc .aidev/*.sh .aidev/runtime/*.sh
}

run_sqlfluff() {
    sqlfluff --version
    sqlfluff lint --dialect postgres --nofail --format yaml --write-output "$out/sqlfluff.yaml" . || return 1
    if grep -q 'code:' "$out/sqlfluff.yaml"; then
        cat "$out/sqlfluff.yaml"
        return 1
    fi
    echo "no sqlfluff violations"
}

run_unit() {
    python3 -m unittest discover -v -s tests/unit -p 'test_*.py'
}

sql_registered() {
    local f missing=0
    while IFS= read -r f; do
        if ! grep -qF "\$SRCPATH/$f\"" scripts/install_app.sh; then
            echo "not applied by scripts/install_app.sh: $f"
            missing=1
        fi
    done < <(find db endpoints -name '*.sql' | sort)
    [ "$missing" -eq 0 ] && echo "every .sql file under db/ and endpoints/ is applied"
    return "$missing"
}

STACK_COMPOSE=.aidev/test-stack.compose.yml
STACK_IMAGES_BY_RELEASE="hafah reputation_tracker hivemind"

# The pins of one image repository in the stack, one per line, deduplicated.
stack_pins_of() {
    grep -oE "registry\.gitlab\.syncad\.com/hive/$1(:[^@\" ]*)?(@sha256:[0-9a-f]*)?" "$STACK_COMPOSE" | sort -u
}

# Every upstream image must be pinned as repo:tag@sha256:<digest> (docker ignores the
# tag); the tag is what ties the digest to .gitlab-ci.yml's UPSTREAM_BRANCH, which
# CI resolves afresh on every run. HAF's tag is a commit, so its branch is recorded
# next to it (x-haf-upstream-branch). Reads only the tree: no registry access.
stack_pins() {
    local branch haf_branch repo pins tag stale=0
    branch="$(sed -n 's/^ *UPSTREAM_BRANCH: *"\{0,1\}\([^"]*\)"\{0,1\} *$/\1/p' .gitlab-ci.yml)"
    if [ -z "$branch" ] || [ "$(printf '%s\n' "$branch" | wc -l)" -ne 1 ]; then
        echo "expected one UPSTREAM_BRANCH in .gitlab-ci.yml, found '$branch'"
        return 1
    fi
    echo ".gitlab-ci.yml UPSTREAM_BRANCH: $branch"
    for repo in haf/testnet $STACK_IMAGES_BY_RELEASE; do
        pins="$(stack_pins_of "$repo")"
        if [ "$(printf '%s\n' "$pins" | grep -c .)" -ne 1 ] \
            || ! grep -qE ":[^@/]+@sha256:[0-9a-f]{64}$" <<<"$pins"; then
            echo "STALE: $STACK_COMPOSE must pin registry.gitlab.syncad.com/hive/$repo once, as repo:tag@sha256:<digest>; found: ${pins:-nothing}"
            stale=1
            continue
        fi
        tag="${pins##*/"$repo":}"; tag="${tag%@*}"
        if [ "$repo" = haf/testnet ]; then
            haf_branch="$(sed -n 's/^x-haf-upstream-branch: *"\{0,1\}\([^"]*\)"\{0,1\} *$/\1/p' "$STACK_COMPOSE")"
            if [ "$haf_branch" != "$branch" ]; then
                echo "STALE: $pins was resolved for HAF branch '${haf_branch}' (x-haf-upstream-branch); expected UPSTREAM_BRANCH $branch: re-pin hive/haf/testnet to what find_haf_image resolves for $branch"
                stale=1
                continue
            fi
        elif [ "$tag" != "$branch" ]; then
            echo "STALE: $pins is release $tag; expected UPSTREAM_BRANCH $branch: re-pin hive/$repo to its $branch image"
            stale=1
            continue
        fi
        echo "ok: $pins"
    done
    [ "$stale" -eq 0 ] || echo "re-pin the stack images together when UPSTREAM_BRANCH moves; see .aidev/README.md"
    return "$stale"
}

wait_for_db() {
    local i found
    for i in $(seq 60); do
        found="$(psql "$ADMIN_URL" -Atc "select 1 from pg_namespace where nspname = 'hivemind_endpoints'" 2>/dev/null)" || true
        [ "$found" = 1 ] && return 0
        echo "waiting for hivemind in $ADMIN_URL ($i)"
        sleep 5
    done
    echo "no hivemind_endpoints schema in $ADMIN_URL: is the stack up?"
    return 1
}

# install_app [INSTALL_APP_OPTION]...: scripts/install_app.sh, its output also in
# $out/install_app.log
install_app() {
    HIVESENSE_GIT_HASH="$(git rev-parse HEAD 2>/dev/null || echo aidev)" \
        bash scripts/install_app.sh --postgres-url="$ADMIN_URL" "$@" 2>&1 | tee "$out/install_app.log"
}

# install [INSTALL_APP_OPTION]...
install() {
    wait_for_db || return 1
    install_app "$@" || return 1
    # The runtime image carries the wrapper, as hivesense's install image does.
    if grep -q "WARNING: install_with_app_lock.py wrapper not found" "$out/install_app.log"; then
        echo "FAIL: install_app.sh ran without install_with_app_lock.py (wrapper not found): the runtime image lacks /usr/local/bin/install_with_app_lock.py or install_app.sh no longer finds it"
        return 1
    fi
    if ! grep -q "Acquired install lock for hivesense" "$out/install_app.log"; then
        echo "FAIL: install_app.sh did not install under the app's install lock (no 'Acquired install lock for hivesense' from install_with_app_lock.py)"
        return 1
    fi
    # What the block processor does at start-up; tests/test_sync_chains.sql
    # expects the primary chain's sync_uuid it mints.
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -Atc "select hivesense_app.init_local_sync_identity()" || return 1
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -f tests/test_sync_chains.sql
}

# query SQL: psql as haf_admin, unaligned tuples only
query() {
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -Atc "$1"
}

# CI's events_id_test (.gitlab-ci.yml, #54), its messages kept: the syncer's real
# ensure_context_detached, imported from the tree, must lift a regressed
# hafd.contexts.events_id back to hive.unreachable_event_id().
events_id() {
    local unreachable before after
    wait_for_db || return 1
    unreachable="$(query "select hive.unreachable_event_id()")" || return 1
    if [ "$(query "select count(*) from hafd.contexts where name = 'hivesense_app'")" != 1 ]; then
        echo "FAIL: hivesense_app context row not found in hafd.contexts"
        return 1
    fi
    query "update hafd.contexts set events_id = 0 where name = 'hivesense_app'" > /dev/null || return 1
    before="$(query "select events_id from hafd.contexts where name = 'hivesense_app'")" || return 1
    echo "Seeded events_id=$before (expected 0); running real ensure_context_detached() from scripts/sync_embeddings.py ..."
    POSTGRES_URI="$ADMIN_URL" python3 -c "import os, sys; sys.path.insert(0, 'scripts'); import psycopg, sync_embeddings as s; c = psycopg.connect(os.environ['POSTGRES_URI']); s.ensure_context_detached(c); c.close(); print('ensure_context_detached ran')" \
        || return 1
    after="$(query "select events_id from hafd.contexts where name = 'hivesense_app'")" || return 1
    echo "events_id after: $after (unreachable_event_id=$unreachable)"
    if [ "$after" != "$unreachable" ]; then
        echo "FAIL: syncer did not park events_id (got $after, expected $unreachable)"
        echo "  Means ensure_context_detached() no longer issues the"
        echo "  'UPDATE hafd.contexts SET events_id = hive.unreachable_event_id()'."
        echo "  This is the issue #54 regression: events_queue would be pinned."
        return 1
    fi
    echo "PASS: syncer parks hivesense_app events_id at unreachable_event_id()"
}

LOCK_HOLDER=aidev-install-lock-holder

# The installed hivesense objects (by oid, so a drop and re-create shows) and its
# configuration row, as one hash.
installed_schema_state() {
    query "select md5(string_agg(x, ',' order by x)) from (
        select 'class ' || c.oid || ' ' || c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
         where n.nspname in ('hivesense_app', 'hivesense_endpoints')
        union all
        select 'proc ' || p.oid || ' ' || p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
         where n.nspname in ('hivesense_app', 'hivesense_endpoints')
        union all
        select 'status ' || s::text from hivesense_app.hivesense_app_status s
    ) objects(x)"
}

# Ends the lock holder's session in the database too: killing the client leaves
# the server side in pg_sleep, holding the lock.
release_install_lock() {
    if [ -n "${holder_pid:-}" ]; then
        kill "$holder_pid" 2>/dev/null
        wait "$holder_pid" 2>/dev/null
    fi
    query "select count(pg_terminate_backend(pid)) from pg_stat_activity where application_name = '$LOCK_HOLDER'" > /dev/null
    echo "released the shared install lock"
}

# CI's lock_skip_test (.gitlab-ci.yml): while another session (a block processor;
# here a background psql) holds the app's shared install lock, install_app.sh
# must skip through install_with_app_lock.py, exit 0 and leave the installed
# schema untouched. Runs after `install`. A subshell, so the EXIT trap releases
# the lock however the check ends.
install_lock() (
    local before after held="" rc=0 i
    holder_pid=""
    trap release_install_lock EXIT
    trap 'exit 143' TERM INT
    wait_for_db || exit 1
    before="$(installed_schema_state)"
    if [ -z "$before" ]; then
        echo "no installed hivesense schema to compare: run after install"
        exit 1
    fi
    psql "$ADMIN_URL?application_name=$LOCK_HOLDER" -v ON_ERROR_STOP=on \
        -c "select pg_advisory_lock_shared(hashtext('hive_fork_manager_app_lock'), hashtext('hivesense'))" \
        -c "select pg_sleep(300)" > "$out/install-lock-holder.log" 2>&1 &
    holder_pid=$!
    for i in $(seq 15); do
        held="$(query "select count(*) from pg_locks l join pg_stat_activity a on a.pid = l.pid
                        where l.locktype = 'advisory' and l.granted and a.application_name = '$LOCK_HOLDER'")"
        [ "$held" = 1 ] && break
        echo "waiting for the shared install lock ($i)"
        sleep 1
    done
    if [ "$held" != 1 ]; then
        echo "FAIL: failed to acquire the shared install lock on hivesense"
        cat "$out/install-lock-holder.log"
        exit 1
    fi
    echo "holding the shared install lock on hivesense; running install_app.sh"
    # Options an install that did run would leave in the configuration row.
    install_app --llm=aidev-lock-skip-check --vector_size=8 || rc=$?
    after="$(installed_schema_state)"
    if [ "$rc" -ne 0 ]; then
        echo "FAIL: install_app.sh exited $rc while the install lock was held (expected 0)"
        exit 1
    fi
    if ! grep -qE "Skipping hivesense install.*lock held by" "$out/install_app.log"; then
        echo "FAIL: expected the wrapper's 'Skipping hivesense install ... lock held by' line"
        echo "  Means: the runtime image lacks install_with_app_lock.py, install_app.sh's"
        echo "  re-exec is broken, or HAF lacks the install-lock helpers."
        exit 1
    fi
    if [ "$after" != "$before" ]; then
        echo "FAIL: the installed schema changed while install_app.sh should have skipped (state $before -> $after)"
        exit 1
    fi
    echo "PASS: install correctly hit the advisory-lock skip path; the installed schema is unchanged"
)

# reinstall [INSTALL_APP_OPTION]...
reinstall() {
    wait_for_db || return 1
    bash scripts/uninstall_app.sh --postgres-url="$ADMIN_URL" || return 1
    install "$@"
}

# The seeded posts (.aidev/seed_posts.sql) in block order; the last one is below
# the token threshold.
SEEDED_POSTS="{900101,900102,900103,900104,900105}"
EMBEDDED_POSTS="900101,900102,900103,900105"
OLLAMA_URL="http://ollama:11434"
EMBEDDING_MODEL="all-minilm:l6-v2"
# CI's slice phase (.gitlab-ci.yml slice_phase, scripts/ci-helpers/reconfigure-hivesense.sh):
# a Matryoshka-trained MiniLM model, its query prefix, 256 of its 384 dims.
SLICE_MODEL="hf.co/mixedbread-ai/mxbai-embed-xsmall-v1:F16"
SLICE_QUERY_PREFIX="Represent this sentence for searching relevant passages: "
SLICE_DIM=256
PCA_DIM=32

# The runtime image has no curl. Without this, a dead server only shows as the
# sync path's unbounded retries in generate_embeddings_for_posts.
# probe_embedding_server MODEL
probe_embedding_server() {
    python3 - "$OLLAMA_URL" "$1" <<'PY'
import json, sys, urllib.error, urllib.request
url, model = sys.argv[1:]
try:
    with urllib.request.urlopen(url + "/api/tags", timeout=10) as resp:
        names = [m.get("name") for m in json.load(resp).get("models", [])]
except (urllib.error.URLError, OSError, ValueError) as e:
    sys.exit(f"embedding server {url} did not answer: {e}")
if model not in names:
    sys.exit(f"embedding server {url} did not answer with {model}: it serves {names}")
print(f"embedding server {url} serves {model}")
PY
}

# embed_seeded_posts MODEL [INSTALL_APP_OPTION]...: reinstall configured for MODEL
# (384 dims, the all-MiniLM-L6-v2 tokenizer), seed and embed the seeded posts,
# check posts_vectors, then build the HNSW index as the block processor does once
# it reaches HAF's head. Later options override the defaults.
embed_seeded_posts() {
    local model="$1" ids got
    shift
    probe_embedding_server "$model" || return 1
    # CI's embedding configuration (docker/ci/compose.yml hivesense-install-schema)
    # except the token threshold. all-MiniLM-L6-v2's tokenizer.json pads every
    # encode to 128 tokens and chunk_post counts per sentence, so no post counts
    # below CI's 75. 200 lies above a one-sentence post (128 padded, ~13 unpadded)
    # and below the long seeded posts (>= 2048 padded, >= 253 unpadded).
    reinstall --llm="$model" --vector_size=384 --tokenizer-model=all-MiniLM-L6-v2 \
        --ollama="$OLLAMA_URL" --document-prefix= --query-prefix= --min-token-threshold=200 "$@" || return 1
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -f .aidev/seed_posts.sql || return 1
    ids="$(query "select hivesense_app.posts_in_range(101, 105)")" || return 1
    if [ "$ids" != "$SEEDED_POSTS" ]; then
        echo "posts_in_range(101, 105) = $ids, expected the seeded posts $SEEDED_POSTS"
        return 1
    fi
    # The sync path retries a dead embedding server forever (ollama_embed with
    # max_retries => NULL). PL/Python only sees the cancel at its next retry
    # notice, so the step can end up to one retry cycle after the timeout.
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on \
        -c "set statement_timeout = '120s'" \
        -c "select * from hivesense_app.generate_embeddings_for_posts('$ids'::int[], false, 0)" \
        -c "select hivesense_app.publish_visible_sync_seq()" || {
        echo "embedding the seeded posts failed or hit the 120s statement_timeout: is the embedding server $OLLAMA_URL answering?"
        return 1
    }
    # Posts with a non-zero 384-dim embedding: every long seeded post, not the short one.
    got="$(query "
        select string_agg(post_id::text, ',' order by post_id) from (
            select post_id from hivesense_app.posts_vectors
             where post_id = any('$ids'::int[])
             group by post_id
            having bool_and(vector_dims(embedding) = 384 and vector_norm(embedding) > 0)
        ) embedded")" || return 1
    if [ "$got" != "$EMBEDDED_POSTS" ]; then
        echo "posts with non-zero 384-dim embeddings: '$got', expected $EMBEDDED_POSTS"
        psql "$ADMIN_URL" -c "select post_id, chunk_number, vector_dims(embedding), vector_norm(embedding)
                                from hivesense_app.posts_vectors order by post_id, chunk_number"
        return 1
    fi
    echo "embedded the seeded posts with $model: $got"
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -c "call hivesense_app.ensure_indexes_are_created()"
}

check_hnsw_index() {
    local name exists
    name="$(query "select hivesense_app.get_hnsw_index_name()")" || return 1
    exists="$(query "select exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                                     where c.relkind = 'i' and n.nspname = 'hivesense_app' and c.relname = '$name')")" || return 1
    if [ "$exists" != t ]; then
        echo "FAIL: HNSW index hivesense_app.$name (get_hnsw_index_name()) does not exist after ensure_indexes_are_created()"
        return 1
    fi
    echo "ok: HNSW index hivesense_app.$name exists"
}

# ranked_posts CALL: the post ids hivesense_app.CALL returns, comma-separated, in rank order
ranked_posts() {
    query "select coalesce(string_agg(post_id::text, ',' order by similarity_order), '') from hivesense_app.$1"
}

sorted_ids() {
    tr , '\n' <<< "$1" | sort -n | paste -sd, -
}

# The paging search (find_nearest_posts_with_embedding, which no endpoint calls)
# against the one-shot one, as tests/integration/api_node/hivesense_search_test.sh
# checks it: a small limit, a limit above the corpus and a continuation. The query
# is the first chunk of a seeded post.
check_paging() {
    local ref="(select embedding::public.vector from hivesense_app.posts_vectors where post_id = 900101 order by chunk_number limit 1)"
    local one_shot got expected second rc=0
    one_shot="$(ranked_posts "find_nearest_posts_with_embedding_one_shot($ref, 100)")" || return 1
    if [ "$(sorted_ids "$one_shot")" != "$EMBEDDED_POSTS" ]; then
        echo "FAIL: find_nearest_posts_with_embedding_one_shot(_limit => 100) returned [$one_shot], expected the embedded seeded posts $EMBEDDED_POSTS"
        return 1
    fi
    echo "one-shot order: [$one_shot]"

    expected="$(cut -d, -f1-2 <<< "$one_shot")"
    if ! got="$(ranked_posts "find_nearest_posts_with_embedding($ref, 2)")"; then
        echo "FAIL: find_nearest_posts_with_embedding(_limit => 2) failed"
        rc=1
    elif [ "$got" != "$expected" ]; then
        echo "FAIL: find_nearest_posts_with_embedding(_limit => 2) returned [$got], expected [$expected] (the one-shot order's first two)"
        rc=1
    else
        echo "ok: find_nearest_posts_with_embedding(_limit => 2) returned [$got]"
    fi

    if ! got="$(ranked_posts "find_nearest_posts_with_embedding($ref, 100)")"; then
        echo "FAIL: find_nearest_posts_with_embedding(_limit => 100) failed"
        rc=1
    elif [ "$(sorted_ids "$got")" != "$EMBEDDED_POSTS" ]; then
        echo "FAIL: find_nearest_posts_with_embedding(_limit => 100) returned [$got], expected each embedded seeded post once ($EMBEDDED_POSTS)"
        rc=1
    else
        echo "ok: find_nearest_posts_with_embedding(_limit => 100) returned [$got]"
    fi

    second="$(cut -d, -f2 <<< "$one_shot")"
    expected="$(cut -d, -f3- <<< "$one_shot")"
    if ! got="$(ranked_posts "find_nearest_posts_with_embedding($ref, 100, NULL, 0, $second)")"; then
        echo "FAIL: find_nearest_posts_with_embedding(_start_post_id => $second) failed"
        rc=1
    elif [ "$got" != "$expected" ]; then
        echo "FAIL: find_nearest_posts_with_embedding(_limit => 100, _start_post_id => $second) returned [$got], expected [$expected] (the one-shot order after $second)"
        rc=1
    else
        echo "ok: find_nearest_posts_with_embedding(_start_post_id => $second) returned [$got]"
    fi
    return "$rc"
}

# search_checks CHECK_SET: the index and paging checks, then CHECK_SET of
# .aidev/hivesense_smoke.py; each runs whichever fails.
search_checks() {
    local rc=0
    check_hnsw_index || rc=1
    check_paging || rc=1
    python3 .aidev/hivesense_smoke.py "$out" "$1" || rc=1
    return "$rc"
}

# config_is EXPECTED: the installed reduction_mode,use_reduced_embeddings,reduced_dims
config_is() {
    local got
    got="$(query "select hivesense_app.reduction_mode() || ',' || hivesense_app.use_reduced_embeddings() || ',' || hivesense_app.reduced_dims()")" || return 1
    if [ "$got" != "$1" ]; then
        echo "FAIL: installed reduction_mode,use_reduced_embeddings,reduced_dims is '$got', expected '$1'"
        return 1
    fi
    echo "ok: reduction_mode,use_reduced_embeddings,reduced_dims = $got"
}

embed_search() {
    embed_seeded_posts "$EMBEDDING_MODEL" && search_checks embed-search
}

# Slice mode keeps no separate reduced vectors: its index and ANN search use the
# first reduced_dims() dims of posts_vectors.embedding.
embed_slice() {
    local got rc=0
    embed_seeded_posts "$SLICE_MODEL" --use-reduced-embeddings=true --reduction-mode=slice \
        --reduced-dim="$SLICE_DIM" --query-prefix="$SLICE_QUERY_PREFIX" || return 1
    config_is "slice,true,$SLICE_DIM" || return 1
    got="$(query "
        select string_agg(post_id::text, ',' order by post_id) from (
            select post_id from hivesense_app.posts_vectors
             where post_id = any('$SEEDED_POSTS'::int[])
             group by post_id
            having bool_and(vector_dims(public.subvector(embedding, 1, hivesense_app.reduced_dims())) = $SLICE_DIM
                            and vector_norm(public.subvector(embedding, 1, hivesense_app.reduced_dims())) > 0)
        ) sliced")" || return 1
    if [ "$got" != "$EMBEDDED_POSTS" ]; then
        echo "FAIL: posts with non-zero $SLICE_DIM-dim slices: '$got', expected $EMBEDDED_POSTS"
        rc=1
    else
        echo "ok: posts with non-zero $SLICE_DIM-dim slices: $got"
    fi
    search_checks embed-slice || rc=1
    return "$rc"
}

# write_pca_matrix FILE: a deterministic orthonormal 384 -> PCA_DIM projection
# (Gram-Schmidt over seeded gaussian vectors) in the JSON shape
# load_reducing_matrix reads. run_pca.py needs numpy and a real corpus: four posts
# would give a degenerate fit.
write_pca_matrix() {
    python3 - "$1" 384 "$PCA_DIM" <<'PY'
import json, math, random, sys
path, dims, rows = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
rng = random.Random(63)
basis = []
while len(basis) < rows:
    v = [rng.gauss(0, 1) for _ in range(dims)]
    for b in basis:
        dot = sum(x * y for x, y in zip(v, b))
        v = [x - dot * y for x, y in zip(v, b)]
    norm = math.sqrt(sum(x * x for x in v))
    basis.append([x / norm for x in v])
with open(path, "w") as f:
    json.dump(basis, f)
print(f"wrote a {rows}x{dims} orthonormal projection to {path}")
PY
}

embed_pca() {
    local matrix="$PWD/$out/pca-matrix.json" got rc=0
    write_pca_matrix "$matrix" || return 1
    embed_seeded_posts "$EMBEDDING_MODEL" --use-reduced-embeddings=true --reduction-mode=pca \
        --reduced-dim="$PCA_DIM" --reduced-matrix-source="$matrix" || return 1
    config_is "pca,true,$PCA_DIM" || return 1
    got="$(query "select count(*) from hivesense_app.reducing_matrix")" || return 1
    if [ "$got" != "$PCA_DIM" ]; then
        echo "FAIL: reducing_matrix has $got rows, expected $PCA_DIM"
        rc=1
    fi
    # Every chunk of a seeded post has a non-zero reduced vector of PCA_DIM dims.
    got="$(query "
        select string_agg(post_id::text, ',' order by post_id) from (
            select pv.post_id from hivesense_app.posts_vectors pv
              left join hivesense_app.posts_vectors_reduced pr using (post_id, chunk_number)
             where pv.post_id = any('$SEEDED_POSTS'::int[])
             group by pv.post_id
            having bool_and(pr.reduced_embedding is not null
                            and vector_dims(pr.reduced_embedding) = $PCA_DIM
                            and vector_norm(pr.reduced_embedding) > 0)
        ) reduced")" || return 1
    if [ "$got" != "$EMBEDDED_POSTS" ]; then
        echo "FAIL: posts with non-zero $PCA_DIM-dim reduced vectors in posts_vectors_reduced: '$got', expected $EMBEDDED_POSTS"
        rc=1
    else
        echo "ok: posts with non-zero $PCA_DIM-dim reduced vectors: $got"
    fi
    search_checks embed-pca || rc=1
    return "$rc"
}

# with_default_restored CMD...: CMD, then, pass or fail, reinstall as `install`
# does, so the steps after it see a fresh default installation
with_default_restored() {
    local rc=0
    "$@" || rc=$?
    echo "== restoring the default installation"
    reinstall || return 1
    return "$rc"
}

