# In a rolled-back transaction: hivemind deletes the embedded pasta post
# (900103) and the other pasta post (900105) is edited in the same block; one
# generate_embeddings_for_posts pass over that block must drop 900103's vectors
# with a tombstone that embedding_updates serves as a delete op, and re-embed
# only 900105 (900103's chunks never reach the embedding server).
deleted_post_checks() {
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -c "set statement_timeout = '600s'" -c "
begin;
set local session_replication_role = replica;
do \$\$
declare
    __seq_before int := (select max(sync_seq) from hivesense_app.posts_vectors);
    __uuid       text := (select sync_uuid::text from hivesense_app.hivesense_app_status where id = 1);
    __stats      record;
    __ops        text;
begin
    update hivemind_app.hive_posts set counter_deleted = 1, block_num = 106 where id = 900103;
    update hivemind_app.hive_posts set block_num = 106 where id = 900105;
    set local session_replication_role = origin;
    select * into __stats
      from hivesense_app.generate_embeddings_for_posts(hivesense_app.posts_in_range(106, 106), false, 0);
    assert __stats.processed_posts = 1 and __stats.discarded_posts = 1, format('stats of the pass: %s', __stats);
    assert not exists (select 1 from hivesense_app.posts_vectors where post_id = 900103),
        'vectors of the deleted post 900103 survived';
    assert (select bool_and(sync_seq > __seq_before) from hivesense_app.posts_vectors where post_id = 900105),
        'the edited post 900105 was not re-embedded';
    perform hivesense_app.publish_visible_sync_seq();
    select string_agg(format('%s:%s', u.op, u.permlink), ',' order by u.sync_seq) into __ops
      from hivesense_endpoints.embedding_updates(__seq_before, 100, __uuid) u;
    assert __ops = 'delete:slow-simmered-tomato-sauce-for-pasta,update:fresh-egg-pasta-with-tomato-basil-sauce',
        format('embedding_updates after the deletion: %s', __ops);
    raise notice 'deleted post checks: PASS (%)', __ops;
end
\$\$;
rollback;"
}

# In a rolled-back transaction: the sauce post's best match, the pasta post
# (900105), is deleted; posts_similar probes liveness after the re-rank and
# must drop it and refill from the remaining candidates, still returning
# result_limit posts in the order they had behind it.
similar_refill_checks() {
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -c "
begin;
do \$\$
declare
    __live    int[] := array(select post_id from hivesense_app.find_nearest_posts_to_post(
                         'aidev-chef', 'slow-simmered-tomato-sauce-for-pasta', 3) order by similarity_order);
    __deleted int[];
begin
    assert __live[1] = 900105 and cardinality(__live) = 3, format('similar posts while all are live: %s', __live);
    update hivemind_app.hive_posts set counter_deleted = 1 where id = 900105;
    __deleted := array(select post_id from hivesense_app.find_nearest_posts_to_post(
                     'aidev-chef', 'slow-simmered-tomato-sauce-for-pasta', 2) order by similarity_order);
    assert __deleted = __live[2:3], format('similar posts with 900105 deleted: %s, expected %s', __deleted, __live[2:3]);
    raise notice 'similar refill checks: PASS (% -> %)', __live, __deleted;
end
\$\$;
rollback;"
}

# In a rolled-back transaction: posts_similar's full posts on the stack's
# hivemind (no _votes_mode yet) embed active_votes; then hivemind's
# create_bridge_post_object is swapped for a stub of the nine-argument one,
# which records the mode it is called with, and the same call must ask for
# vote-free posts (_votes_mode 1, _top_votes 0) for the observer and return the
# same posts, in the same order, with nothing else changed.
similar_votes_mode_checks() {
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -c "
begin;
create temp table embedded_votes on commit drop as
select hivesense_endpoints.posts_similar('aidev-chef', 'slow-simmered-tomato-sauce-for-pasta', 0, 3, 3, 'aidev-witness')::jsonb as posts;
do \$\$
declare
    __posts jsonb := (select posts from embedded_votes);
begin
    assert jsonb_array_length(__posts) = 3, format('full similar posts: %s', __posts);
    assert (select bool_and(p ? 'active_votes' and not p ? 'observer_vote') from jsonb_array_elements(__posts) p),
        format('full similar posts without _votes_mode lack active_votes: %s', __posts);
end
\$\$;
alter function hivemind_postgrest_utilities.create_bridge_post_object(integer, record, integer, text[], boolean, boolean, jsonb)
    rename to create_bridge_post_object_embedded_votes;
create function hivemind_postgrest_utilities.create_bridge_post_object(
    _observer_id integer, _row record, _truncate_body_len integer, _reblogged_by text[], _set_is_pinned_field boolean,
    _update_reblogs_field boolean, _replies jsonb default null, _votes_mode smallint default 0, _top_votes integer default 0)
returns jsonb language plpgsql stable as \$f\$
begin
    return hivemind_postgrest_utilities.create_bridge_post_object_embedded_votes(
               _observer_id, _row, _truncate_body_len, _reblogged_by, _set_is_pinned_field, _update_reblogs_field, _replies)
           - 'active_votes'
           || jsonb_build_object('votes_mode', _votes_mode, 'top_votes', _top_votes, 'observer_id', _observer_id);
end
\$f\$;
do \$\$
declare
    __before   jsonb := (select jsonb_agg(p - 'active_votes' order by o)
                           from embedded_votes, jsonb_array_elements(posts) with ordinality e(p, o));
    __posts    jsonb := hivesense_endpoints.posts_similar('aidev-chef', 'slow-simmered-tomato-sauce-for-pasta', 0, 3, 3, 'aidev-witness')::jsonb;
    __observer int := (select id from hivemind_app.hive_accounts where name = 'aidev-witness');
begin
    assert (select bool_and(not p ? 'active_votes' and p->>'votes_mode' = '1' and p->>'top_votes' = '0'
                            and (p->>'observer_id')::int = __observer)
              from jsonb_array_elements(__posts) p),
        format('full similar posts with _votes_mode are not vote-free for observer %s: %s', __observer, __posts);
    assert (select jsonb_agg(p - 'votes_mode' - 'top_votes' - 'observer_id' order by o)
              from jsonb_array_elements(__posts) with ordinality e(p, o)) = __before,
        format('vote-free similar posts %s differ from %s beyond active_votes', __posts, __before);
    raise notice 'similar votes mode checks: PASS';
end
\$\$;
rollback;"
}

