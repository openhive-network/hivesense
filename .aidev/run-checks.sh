#!/usr/bin/env bash
# The step functions are called indirectly, through `step`.
# shellcheck disable=SC2317,SC2329
# The checks AIDEV's verification slots run (.aidev/project.yaml), as one junit
# report per suite: each named step is a test case, its log the failure body.
#
#   .aidev/run-checks.sh <suite> <step>...
#
#   - shellcheck      ShellCheck at warning severity on every *.sh (the files CI's
#                     lint_bash_scripts checks), at default severity on .aidev/'s own
#   - sqlfluff        `sqlfluff lint` with the repository's .sqlfluff (CI's
#                     lint_sql_scripts, which fails on any violation .sqlfluff
#                     does not list under `warnings`)
#   - unit            tests/unit with python's unittest (no database, no network)
#   - sql-registered  every .sql file under db/ and endpoints/ is applied by
#                     scripts/install_app.sh (a file it misses never reaches a database)
#   - stack-pins      the four upstream images of .aidev/test-stack.compose.yml are
#                     pinned as repo:tag@sha256 for .gitlab-ci.yml's UPSTREAM_BRANCH,
#                     and the votes-mode hivemind as repo:tag@sha256
#   - install         scripts/install_app.sh into the stack's HAF database
#                     (HIVESENSE_TEST_DB_HOST, default `haf`), which already has
#                     hivemind installed, through install_with_app_lock.py (its log
#                     must not carry the wrapper-not-found WARNING); then the block
#                     processor's start-up identity (init_local_sync_identity),
#                     tests/test_sync_chains.sql, tests/test_early_block_processing.sql
#                     and tests/test_deleted_posts.sql; then
#                     .aidev/endpoint_volatility_check.sql (no VOLATILE function in
#                     hivesense_endpoints) and root() by hivesense_user, read only
#   - events-id       CI's events_id_test (#54): seed hafd.contexts.events_id = 0
#                     for hivesense_app, run scripts/sync_embeddings.py's
#                     ensure_context_detached, expect hive.unreachable_event_id()
#   - install-lock    CI's lock_skip_test: while another session holds the app's
#                     shared install lock, install_app.sh skips, exits 0 and leaves
#                     the installed schema as it was
#   - reinstall       scripts/uninstall_app.sh, then install again
#   - registry        hivesense's row in HAF's application registry: named
#                     `hivesense`, its hivemind dependency and health function
#                     (a missing core function refuses the block-processor lock),
#                     the paused flag kept by a reinstall, and an install over a
#                     leftover `hivesense_app` row failing, naming it
#   - hivemind-reinstall  hivemind's role dropped and recreated (its uninstall and
#                     reinstall, its objects kept) under an installed hivesense; then
#                     install must restore both hivesense roles' hivemind membership.
#                     Also: with no hivemind role, builtin_roles.sql fails naming it
#   - embed-search    reinstall configured as CI's sync job (all-minilm:l6-v2, 384
#                     dims, the stack's `ollama`; token threshold 200), seed
#                     .aidev/seed_posts.sql, embed the seeded posts with
#                     generate_embeddings_for_posts, check what posts_vectors
#                     holds, build the HNSW index and check it exists, then the
#                     embedding-backed calls of
#                     .aidev/hivesense_smoke.py (one junit case per call), then
#                     (rolled back) a deletion of an embedded seeded post in block
#                     processing and its delete op in embedding_updates, and
#                     posts_similar's full posts with and without hivemind's
#                     _votes_mode (the vote-free call); finally
#                     reinstall as `install` does, so the steps after it see that state
#   - votes-mode      on the stack's second HAF (HIVESENSE_TEST_VOTES_MODE_DB_HOST,
#                     default `haf-votes-mode`), whose hivemind has
#                     create_bridge_post_object's _votes_mode: install, seed and
#                     embed as embed-search, then posts_similar's full posts must
#                     carry no active_votes, the observer's vote as observer_vote,
#                     and otherwise equal hivemind's seven-argument output
#   - embed-slice     embed-search in CI's slice configuration
#                     (mxbai-embed-xsmall-v1, Matryoshka slice to 256 dims)
#   - embed-pca       embed-search's embedding in PCA mode, with a projection
#                     matrix generated by the step: reduced vectors and search
#   - api-smoke       PostgREST over the installed schema, the calls in
#                     .aidev/hivesense_smoke.py; one junit case per call
#
# The steps from install on need the HAF stack (.aidev/test-stack.compose.yml).
# Reports go to test-results/<suite>/: junit.xml (one case per step) plus one
# <check set>.xml per .aidev/hivesense_smoke.py run.
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

suite="${1:?usage: $0 <suite> <step>...}"; shift
out="test-results/$suite"
rm -rf "$out"; mkdir -p "$out"
cases="$out/cases.tsv"; : > "$cases"

DB_HOST="${HIVESENSE_TEST_DB_HOST:-haf}"
ADMIN_URL="postgresql://haf_admin@$DB_HOST/haf_block_log"
export HIVESENSE_TEST_USER_URL="postgresql://hivesense_user@$DB_HOST/haf_block_log"

status=0
# record CASES_FILE NAME RC SECONDS LOG
record() {
    if [ "$3" -eq 0 ]; then
        printf 'case\t%s\tpass\t%s\t\n' "$2" "$4" >> "$1"
    else
        printf 'case\t%s\tfail\t%s\texit %s\t%s\n' "$2" "$4" "$3" "$5" >> "$1"
    fi
}

step() {
    local name="$1"; shift
    local log="$out/$name.log" t0=$SECONDS rc=0
    echo "== $name" >&2
    "$@" > "$log" 2>&1 < /dev/null || rc=$?
    [ "$rc" -eq 0 ] || { status=1; tail -40 "$log" >&2; }
    record "$cases" "$name" "$rc" "$((SECONDS - t0))" "$log"
}

run_shellcheck() {
    shellcheck --version | head -2
    # The project's scripts carry notes (SC2015) today; warnings are the floor.
    find . -name .git -prune -o -name .aidev -prune -o -name test-results -prune -o -type f -name '*.sh' -print0 \
        | xargs -0 shellcheck -S warning -f gcc || return 1
    shellcheck -f gcc .aidev/*.sh .aidev/runtime/*.sh
}

run_sqlfluff() {
    sqlfluff --version
    sqlfluff lint --dialect postgres --nofail --format yaml --write-output "$out/sqlfluff.yaml" . || return 1
    if grep -q 'warning: false' "$out/sqlfluff.yaml"; then
        cat "$out/sqlfluff.yaml"
        return 1
    fi
    echo "no sqlfluff violations"
}

run_unit() {
    python3 -m unittest discover -v -s tests/unit -p 'test_*.py'
}

sql_registered() {
    local f missing=0
    while IFS= read -r f; do
        if ! grep -qF "\$SRCPATH/$f\"" scripts/install_app.sh; then
            echo "not applied by scripts/install_app.sh: $f"
            missing=1
        fi
    done < <(find db endpoints -name '*.sql' | sort)
    [ "$missing" -eq 0 ] && echo "every .sql file under db/ and endpoints/ is applied"
    return "$missing"
}

STACK_COMPOSE=.aidev/test-stack.compose.yml
STACK_IMAGES_BY_RELEASE="hafah reputation_tracker hivemind"

# The pins of one image repository in the stack, one per line, deduplicated; the
# votes-mode hivemind (x-hivemind-votes-mode-image) is not a release pin.
stack_pins_of() {
    grep -v '^x-hivemind-votes-mode-image:' "$STACK_COMPOSE" \
        | grep -oE "registry\.gitlab\.syncad\.com/hive/$1(:[^@\" ]*)?(@sha256:[0-9a-f]*)?" | sort -u
}

# Every upstream image must be pinned as repo:tag@sha256:<digest> (docker ignores the
# tag); the tag is what ties the digest to .gitlab-ci.yml's UPSTREAM_BRANCH, which
# CI resolves afresh on every run. HAF's tag is a commit, so its branch is recorded
# next to it (x-haf-upstream-branch). The other images are releases (x-apps-release):
# UPSTREAM_BRANCH's, or, while HAF follows develop, which has no app releases, the
# newest release. Reads only the tree: no registry access.
stack_pins() {
    local branch haf_branch release repo pins tag stale=0
    branch="$(sed -n 's/^ *UPSTREAM_BRANCH: *"\{0,1\}\([^"]*\)"\{0,1\} *$/\1/p' .gitlab-ci.yml)"
    if [ -z "$branch" ] || [ "$(printf '%s\n' "$branch" | wc -l)" -ne 1 ]; then
        echo "expected one UPSTREAM_BRANCH in .gitlab-ci.yml, found '$branch'"
        return 1
    fi
    echo ".gitlab-ci.yml UPSTREAM_BRANCH: $branch"
    release="$(sed -n 's/^x-apps-release: *"\{0,1\}\([^"]*\)"\{0,1\} *$/\1/p' "$STACK_COMPOSE")"
    if [ -z "$release" ] || { [ "$branch" != develop ] && [ "$release" != "$branch" ]; }; then
        echo "STALE: $STACK_COMPOSE x-apps-release is '${release}'; expected UPSTREAM_BRANCH $branch (or a release while it is develop)"
        stale=1
    fi
    for repo in haf/testnet $STACK_IMAGES_BY_RELEASE; do
        pins="$(stack_pins_of "$repo")"
        if [ "$(printf '%s\n' "$pins" | grep -c .)" -ne 1 ] \
            || ! grep -qE ":[^@/]+@sha256:[0-9a-f]{64}$" <<<"$pins"; then
            echo "STALE: $STACK_COMPOSE must pin registry.gitlab.syncad.com/hive/$repo once, as repo:tag@sha256:<digest>; found: ${pins:-nothing}"
            stale=1
            continue
        fi
        tag="${pins##*/"$repo":}"; tag="${tag%@*}"
        if [ "$repo" = haf/testnet ]; then
            haf_branch="$(sed -n 's/^x-haf-upstream-branch: *"\{0,1\}\([^"]*\)"\{0,1\} *$/\1/p' "$STACK_COMPOSE")"
            if [ "$haf_branch" != "$branch" ]; then
                echo "STALE: $pins was resolved for HAF branch '${haf_branch}' (x-haf-upstream-branch); expected UPSTREAM_BRANCH $branch: re-pin hive/haf/testnet to what find_haf_image resolves for $branch"
                stale=1
                continue
            fi
        elif [ "$tag" != "$release" ]; then
            echo "STALE: $pins is release $tag; expected x-apps-release $release: re-pin hive/$repo to its $release image"
            stale=1
            continue
        fi
        echo "ok: $pins"
    done
    pins="$(sed -n 's/^x-hivemind-votes-mode-image: *&[^ ]* *//p' "$STACK_COMPOSE")"
    if ! grep -qxE "registry\.gitlab\.syncad\.com/hive/hivemind:[^@/]+@sha256:[0-9a-f]{64}" <<<"$pins"; then
        echo "STALE: $STACK_COMPOSE x-hivemind-votes-mode-image must pin registry.gitlab.syncad.com/hive/hivemind as repo:tag@sha256:<digest>; found: ${pins:-nothing}"
        stale=1
    else
        echo "ok: $pins (votes-mode hivemind)"
    fi
    [ "$stale" -eq 0 ] || echo "re-pin the stack images together when UPSTREAM_BRANCH moves; see .aidev/README.md"
    return "$stale"
}

wait_for_db() {
    local i found
    for i in $(seq 60); do
        found="$(psql "$ADMIN_URL" -Atc "select 1 from pg_namespace where nspname = 'hivemind_endpoints'" 2>/dev/null)" || true
        [ "$found" = 1 ] && return 0
        echo "waiting for hivemind in $ADMIN_URL ($i)"
        sleep 5
    done
    echo "no hivemind_endpoints schema in $ADMIN_URL: is the stack up?"
    return 1
}

# install_app [INSTALL_APP_OPTION]...: scripts/install_app.sh, its output also in
# $out/install_app.log
install_app() {
    HIVESENSE_GIT_HASH="$(git rev-parse HEAD 2>/dev/null || echo aidev)" \
        bash scripts/install_app.sh --postgres-url="$ADMIN_URL" "$@" 2>&1 | tee "$out/install_app.log"
}

# install [INSTALL_APP_OPTION]...
install() {
    wait_for_db || return 1
    install_app "$@" || return 1
    # The runtime image carries the wrapper, as hivesense's install image does.
    if grep -q "WARNING: install_with_app_lock.py wrapper not found" "$out/install_app.log"; then
        echo "FAIL: install_app.sh ran without install_with_app_lock.py (wrapper not found): the runtime image lacks /usr/local/bin/install_with_app_lock.py or install_app.sh no longer finds it"
        return 1
    fi
    if ! grep -q "Acquired install lock for hivesense" "$out/install_app.log"; then
        echo "FAIL: install_app.sh did not install under the app's install lock (no 'Acquired install lock for hivesense' from install_with_app_lock.py)"
        return 1
    fi
    # What the block processor does at start-up; tests/test_sync_chains.sql
    # expects the primary chain's sync_uuid it mints.
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -Atc "select hivesense_app.init_local_sync_identity()" || return 1
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -f tests/test_sync_chains.sql || return 1
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -f tests/test_early_block_processing.sql || return 1
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -f tests/test_deleted_posts.sql || return 1
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -f .aidev/endpoint_volatility_check.sql || return 1
    # As PostgREST runs a GET: the API role, in a read-only transaction.
    psql "$HIVESENSE_TEST_USER_URL" -v ON_ERROR_STOP=on -Atc "begin read only" \
        -c "select jsonb_typeof(hivesense_endpoints.root()::jsonb)" -c "rollback"
}

# query SQL: psql as haf_admin, unaligned tuples only
query() {
    psql "$ADMIN_URL" -v ON_ERROR_STOP=on -Atc "$1"
}

# CI's events_id_test (.gitlab-ci.yml, #54), its messages kept: the syncer's real
# ensure_context_detached, imported from the tree, must lift a regressed
# hafd.contexts.events_id back to hive.unreachable_event_id().
events_id() {
    local unreachable before after
    wait_for_db || return 1
    unreachable="$(query "select hive.unreachable_event_id()")" || return 1
    if [ "$(query "select count(*) from hafd.contexts where name = 'hivesense_app'")" != 1 ]; then
        echo "FAIL: hivesense_app context row not found in hafd.contexts"
        return 1
    fi
    query "update hafd.contexts set events_id = 0 where name = 'hivesense_app'" > /dev/null || return 1
    before="$(query "select events_id from hafd.contexts where name = 'hivesense_app'")" || return 1
    echo "Seeded events_id=$before (expected 0); running real ensure_context_detached() from scripts/sync_embeddings.py ..."
    POSTGRES_URI="$ADMIN_URL" python3 -c "import os, sys; sys.path.insert(0, 'scripts'); import psycopg, sync_embeddings as s; c = psycopg.connect(os.environ['POSTGRES_URI']); s.ensure_context_detached(c); c.close(); print('ensure_context_detached ran')" \
        || return 1
    after="$(query "select events_id from hafd.contexts where name = 'hivesense_app'")" || return 1
    echo "events_id after: $after (unreachable_event_id=$unreachable)"
    if [ "$after" != "$unreachable" ]; then
        echo "FAIL: syncer did not park events_id (got $after, expected $unreachable)"
        echo "  Means ensure_context_detached() no longer issues the"
        echo "  'UPDATE hafd.contexts SET events_id = hive.unreachable_event_id()'."
        echo "  This is the issue #54 regression: events_queue would be pinned."
        return 1
    fi
    echo "PASS: syncer parks hivesense_app events_id at unreachable_event_id()"
}

LOCK_HOLDER=aidev-install-lock-holder

# The installed hivesense objects (by oid, so a drop and re-create shows) and its
# configuration row, as one hash.
installed_schema_state() {
    query "select md5(string_agg(x, ',' order by x)) from (
        select 'class ' || c.oid || ' ' || c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
         where n.nspname in ('hivesense_app', 'hivesense_endpoints')
        union all
        select 'proc ' || p.oid || ' ' || p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
         where n.nspname in ('hivesense_app', 'hivesense_endpoints')
        union all
        select 'status ' || s::text from hivesense_app.hivesense_app_status s
    ) objects(x)"
}

# Ends the lock holder's session in the database too: killing the client leaves
# the server side in pg_sleep, holding the lock.
release_install_lock() {
    if [ -n "${holder_pid:-}" ]; then
        kill "$holder_pid" 2>/dev/null
        wait "$holder_pid" 2>/dev/null
    fi
    query "select count(pg_terminate_backend(pid)) from pg_stat_activity where application_name = '$LOCK_HOLDER'" > /dev/null
    echo "released the shared install lock"
}

# CI's lock_skip_test (.gitlab-ci.yml): while another session (a block processor;
# here a background psql) holds the app's shared install lock, install_app.sh
# must skip through install_with_app_lock.py, exit 0 and leave the installed
# schema untouched. Runs after `install`. A subshell, so the EXIT trap releases
# the lock however the check ends.
install_lock() (
    local before after held="" rc=0 i
    holder_pid=""
    trap release_install_lock EXIT
    trap 'exit 143' TERM INT
    wait_for_db || exit 1
    before="$(installed_schema_state)"
    if [ -z "$before" ]; then
        echo "no installed hivesense schema to compare: run after install"
        exit 1
    fi
    psql "$ADMIN_URL?application_name=$LOCK_HOLDER" -v ON_ERROR_STOP=on \
        -c "select pg_advisory_lock_shared(hashtext('hive_fork_manager_app_lock'), hashtext('hivesense'))" \
        -c "select pg_sleep(300)" > "$out/install-lock-holder.log" 2>&1 &
    holder_pid=$!
    for i in $(seq 15); do
        held="$(query "select count(*) from pg_locks l join pg_stat_activity a on a.pid = l.pid
                        where l.locktype = 'advisory' and l.granted and a.application_name = '$LOCK_HOLDER'")"
        [ "$held" = 1 ] && break
        echo "waiting for the shared install lock ($i)"
        sleep 1
    done
    if [ "$held" != 1 ]; then
        echo "FAIL: failed to acquire the shared install lock on hivesense"
        cat "$out/install-lock-holder.log"
        exit 1
    fi
    echo "holding the shared install lock on hivesense; running install_app.sh"
    # Options an install that did run would leave in the configuration row.
    install_app --llm=aidev-lock-skip-check --vector_size=8 || rc=$?
    after="$(installed_schema_state)"
    if [ "$rc" -ne 0 ]; then
        echo "FAIL: install_app.sh exited $rc while the install lock was held (expected 0)"
        exit 1
    fi
    if ! grep -qE "Skipping hivesense install.*lock held by" "$out/install_app.log"; then
        echo "FAIL: expected the wrapper's 'Skipping hivesense install ... lock held by' line"
        echo "  Means: the runtime image lacks install_with_app_lock.py, install_app.sh's"
        echo "  re-exec is broken, or HAF lacks the install-lock helpers."
        exit 1
    fi
    if [ "$after" != "$before" ]; then
        echo "FAIL: the installed schema changed while install_app.sh should have skipped (state $before -> $after)"
        exit 1
    fi
    echo "PASS: install correctly hit the advisory-lock skip path; the installed schema is unchanged"
)

# reinstall [INSTALL_APP_OPTION]...
reinstall() {
    wait_for_db || return 1
    bash scripts/uninstall_app.sh --postgres-url="$ADMIN_URL" || return 1
    install "$@"
}

# The registrations holding hivesense's context, as name=contexts
registrations() {
    query "select coalesce(string_agg(name || '=' || array_to_string(contexts, ','), ' ' order by name), '')
             from hafd.applications where name in ('hivesense', 'hivesense_app') or 'hivesense_app' = any(contexts)"
}

# The registrations holding hivemind's context, comma separated
hivemind_registration() {
    query "select coalesce(string_agg(name, ',' order by name), '') from hafd.applications where contexts @> array['hivemind_app']"
}

# expect_hivemind_dependency NAME: hivesense's dependencies are exactly NAME
expect_hivemind_dependency() {
    local got
    got="$(query "select coalesce(string_agg(depends_on, ',' order by depends_on), '')
                    from hafd.application_dependencies where application = 'hivesense'")" || return 1
    if [ "$got" != "$1" ]; then
        echo "FAIL: hivemind is registered as '$1' but hivesense depends on '$got'"
        return 1
    fi
    echo "ok: hivesense depends on hivemind's registration $1"
}

# An install over a stub hivemind registration (context hivemind_app) named
# `hivemind` (hivemind's lock name) and named `hivemind_app` (before its
# rename): the dependency on that name. Over none (a hivemind that skipped
# registration) and over two (a leftover) the install fails, naming the problem. hivemind's own registration and the dependencies on it are put back as they were.
hivemind_dependency_stubs() (
    local saved_app saved_deps name rc=0
    saved_app="$(query "select a::text from hafd.applications a where contexts @> array['hivemind_app']")" || exit 1
    saved_deps="$(query "select coalesce(string_agg(quote_literal(d::text), ',' order by d::text), '')
                           from hafd.application_dependencies d join hafd.applications a on a.name in (d.application, d.depends_on)
                          where a.contexts @> array['hivemind_app'] and d.application <> 'hivesense'")" || exit 1
    restore_hivemind() {
        query "delete from hafd.applications where contexts @> array['hivemind_app']" > /dev/null || return 1
        query "insert into hafd.applications select (\$aidev\$$saved_app\$aidev\$::hafd.applications).*" > /dev/null || return 1
        if [ -n "$saved_deps" ]; then
            query "insert into hafd.application_dependencies
                   select (d::hafd.application_dependencies).* from unnest(array[$saved_deps]) d" > /dev/null || return 1
        fi
        echo "restored hivemind's registration"
    }
    trap 'restore_hivemind || exit 1' EXIT
    trap 'exit 143' TERM INT

    for name in hivemind hivemind_app; do
        query "delete from hafd.applications where contexts @> array['hivemind_app'];
               insert into hafd.applications(name, contexts, owner) values ('$name', array['hivemind_app'], 'hivemind')" > /dev/null || exit 1
        if ! install_app; then
            echo "FAIL: install_app.sh failed over a stub hivemind registration '$name'"
            rc=1
            continue
        fi
        expect_hivemind_dependency "$name" || rc=1
    done

    query "delete from hafd.applications where contexts @> array['hivemind_app']" > /dev/null || exit 1
    if install_app; then
        echo "FAIL: install_app.sh succeeded with no hivemind registered on a HAF with the application registry"
        rc=1
    elif ! grep -qF "hivemind is not registered in the HAF application registry" "$out/install_app.log" \
            || ! grep -qF "registry not available" "$out/install_app.log"; then
        echo "FAIL: install_app.sh failed with no hivemind registered without naming the missing registration"
        rc=1
    else
        echo "ok: with no hivemind registered, the install fails naming the missing registration"
    fi

    query "delete from hafd.applications where contexts @> array['hivemind_app'];
           insert into hafd.applications(name, contexts, owner)
           values ('hivemind', array['hivemind_app'], 'hivemind'), ('hivemind_app', array['hivemind_app'], 'hivemind')" > /dev/null || exit 1
    if install_app; then
        echo "FAIL: install_app.sh succeeded over two registrations holding context hivemind_app"
        rc=1
    elif ! grep -qF "its context hivemind_app is registered by applications {hivemind,hivemind_app}" "$out/install_app.log"; then
        echo "FAIL: install_app.sh failed over two hivemind registrations without naming them"
        rc=1
    else
        echo "ok: two registrations holding context hivemind_app fail the install, naming them"
    fi
    exit "$rc"
)

# hivesense's row in HAF's application registry, after install: registered as
# `hivesense` (its block-processor lock name) holding its context, depending on
# hivemind's registration (found by its context, under either name; with stub
# registrations under both; none or two fail the install), and with
# install_health() as its health function on a HAF that takes one; a missing core
# object then refuses the block-processor lock. A reinstall keeps the paused flag.
# A leftover `hivesense_app` row makes the install fail naming it, and leaves the
# row as it was. Ends with a default installation, pass or fail.
registry() (
    local got rc=0 before after
    trap 'exit 143' TERM INT
    wait_for_db || exit 1
    got="$(registrations)" || exit 1
    if [ "$got" != "hivesense=hivesense_app" ]; then
        echo "FAIL: expected one registration hivesense=hivesense_app holding the context; found '$got'"
        exit 1
    fi
    echo "ok: registered as hivesense, holding context hivesense_app"

    got="$(hivemind_registration)" || exit 1
    if [ -z "$got" ] || [[ "$got" == *,* ]]; then
        echo "FAIL: expected one hivemind registration holding context hivemind_app; found '$got'"
        exit 1
    fi
    expect_hivemind_dependency "$got" || exit 1
    hivemind_dependency_stubs || exit 1

    got="$(query "select coalesce(hivesense_app.install_health(), 'NULL')")" || exit 1
    if [ "$got" != NULL ]; then
        echo "FAIL: install_health() reports '$got' on a complete install"
        exit 1
    fi
    got="$(psql "$ADMIN_URL" -q -v ON_ERROR_STOP=on -At -c begin \
             -c "drop table hivesense_app.sync_chains cascade" \
