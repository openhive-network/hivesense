-- noqa: disable=CP03
SET ROLE hivesense_owner;

DO $BODY$
DECLARE 
  __schema_name VARCHAR;
  __vector_size INT := current_setting('PG_TEMP.VECTOR_SIZE', TRUE)::INT;
  __parallel_workers INT := current_setting('PG_TEMP.PARALLEL_WORKERS', TRUE)::INT;
  __store_halfvec_embeddings BOOLEAN := current_setting('PG_TEMP.STORE_HALFVEC_EMBEDDINGS', TRUE)::BOOLEAN;
  synchronization_stages hive.application_stages;
  __worker INT;
BEGIN
  SHOW SEARCH_PATH INTO __schema_name;

  ASSERT __parallel_workers IS NOT NULL, 'No parallel_workers';
  ASSERT __parallel_workers > 0, 'Parallel workers less than 0';

  synchronization_stages := ARRAY[( 'MASSIVE_PROCESSING', 11, 100000, '30 seconds' ), hive.live_stage()]::hive.application_stages;

  RAISE NOTICE 'HiveSense will be installed in schema % with context %', __schema_name, __schema_name;

  CREATE TABLE IF NOT EXISTS hivesense_app_status
  (
    id SERIAL PRIMARY KEY,
    continue_processing BOOLEAN NOT NULL,
    parallel_workers INT,
    llm TEXT,
    ollama TEXT,
    start_block INT,
    embedding_batch_size INT, -- send this many texts to ollama in a single API call, it will generate this many embedding vectors and sent them back
    tokenizer_model TEXT, -- model used for counting tokens, must be compatible with `llm`'s tokenizer
    tokens_per_chunk INT, -- for chunking posts, number of tokens per chunk (should not `llm`'s the model's max tokens)
    overlap_amount REAL, -- for chunking posts, try to include this amount of overlap with the prevoius chunk to add context (0.15 = 15%)
    use_halfvec_index BOOLEAN NOT NULL DEFAULT false, -- if true, index using 16-bit floats, slight loss of accuracy
    store_halfvec_embeddings BOOLEAN NOT NULL DEFAULT false, -- if true, both full & reduced embeddings are halfvec
    use_reduced_embeddings   BOOLEAN NOT NULL DEFAULT false, -- enable 2-stage ANN+rering
    reduced_dim             INT,                            -- required when ^ = true
    reduction_mode          TEXT    NOT NULL DEFAULT 'none', -- 'none', 'pca', or 'slice' (matryoshka)
    hnsw_m                  INT    NOT NULL DEFAULT 32,
    hnsw_ef_construction    INT    NOT NULL DEFAULT 400,
    default_ef_search INT    NOT NULL DEFAULT 500,
    minimum_ann_candidates INT   NOT NULL DEFAULT 1000,
    allow_debugging   BOOLEAN NOT NULL DEFAULT FALSE,
    document_prefix     TEXT    NOT NULL DEFAULT 'passage: ', -- prefix used when generating embeddings from posts
    query_prefix        TEXT    NOT NULL DEFAULT 'query: ', -- prefix used when generating embeddings from query strings
    embedding_dimensionality INT NOT NULL DEFAULT 768, -- size of embedding vectors generated by `llm`
    min_token_threshold INT NOT NULL DEFAULT 75, -- don't generate embeddings for posts shorter than this number of tokens
    min_token_search_threshold INT NOT NULL DEFAULT 0, -- ignore posts < this size when *searching* (0 = disabled)
    max_embeddings_per_post INT, -- max number of chunks per post, NULL for unlimited
    desired_maintenance_work_mem_gb INT NOT NULL DEFAULT 28, -- target maintenance_work_mem (GB)
    advisory_lock_namespace_begin INT, -- start of advisory lock namespace, if running multiple instances, use different values (separated by, say, 10 or so)
    max_visible_sync_seq INT NOT NULL DEFAULT 0, -- highest sync sequence number to publish, anything higher may have gaps that will be filled later
    syncing_embeddings BOOLEAN, -- true if we're syncing emeddings, false if computing locally
    sync_uuid uuid -- uuid tracking what server we're syncing embeddings from (or whether we're generating them ourselves)
  );

  IF NOT hive.app_context_exists(__schema_name) THEN
    PERFORM hive.app_create_context(_name => __schema_name,
                                    _schema => __schema_name,
                                    _is_forking => False,
                                    _stages => synchronization_stages);
  END IF;

  CREATE TABLE IF NOT EXISTS version(
    schema_hash TEXT,
    runtime_hash TEXT
  );

  -- Monotonic sequence that orders every logical operation
  CREATE SEQUENCE IF NOT EXISTS hivesense_app.sync_seq;

  -- This table will hold, for every post_id that we generate embeddings for,
  -- the total number of tokens in that post.  We insert one row per post_id.
  -- note: the commented-out foreign key to hivemind_app is believed to cause deadlock,
  -- particularly when hivesense is syncing alongside hivemind
  CREATE TABLE IF NOT EXISTS hivesense_app.post_data
  (
      post_id            INT PRIMARY KEY, -- REFERENCES hivemind_app.hive_posts(id) DEFERRABLE INITIALLY DEFERRED,
      number_of_tokens   INT NOT NULL,
      last_vectors_block INT NOT NULL DEFAULT -1
  );

  -- extend to public, to find vector from pgvector
  EXECUTE format( 'SET SEARCH_PATH TO %s, public', __schema_name );
  IF __store_halfvec_embeddings THEN
    EXECUTE format($$
      CREATE TABLE IF NOT EXISTS posts_vectors
      (
          post_id      INT NOT NULL REFERENCES hivesense_app.post_data(post_id),
          chunk_number INT NOT NULL,
          embedding    public.halfvec(%s) NOT NULL,
          sync_seq     INT NOT NULL,          -- drawn from hivesense_app.sync_seq
          PRIMARY KEY (post_id, chunk_number)
      );
    $$, __vector_size);
  ELSE
    EXECUTE format($$
      CREATE TABLE IF NOT EXISTS posts_vectors
      (
          post_id      INT NOT NULL REFERENCES hivesense_app.post_data(post_id),
          chunk_number INT NOT NULL,
          embedding    vector(%s) NOT NULL,
          sync_seq     INT NOT NULL,          -- drawn from hivesense_app.sync_seq
          PRIMARY KEY (post_id, chunk_number)
      );
    $$, __vector_size);
  END IF;

  /* ————————————————————————————————————————————————————————————
   * REDUCED-SIZE EMBEDDINGS (only created when flag is TRUE)
   * ————————————————————————————————————————————————————————————*/
  IF current_setting('PG_TEMP.USE_REDUCED_EMBEDDINGS',   TRUE)::BOOLEAN
     AND COALESCE(current_setting('PG_TEMP.REDUCTION_MODE', TRUE), 'none') <> 'slice' THEN
    EXECUTE format($$
      CREATE TABLE IF NOT EXISTS posts_vectors_reduced (
          post_id      INT NOT NULL,
          chunk_number INT NOT NULL,
          reduced_embedding %s NOT NULL,
          PRIMARY KEY (post_id, chunk_number),
          FOREIGN KEY (post_id, chunk_number)
            REFERENCES hivesense_app.posts_vectors(post_id, chunk_number)
            ON DELETE CASCADE
      );
    $$,
      CASE
        WHEN __store_halfvec_embeddings THEN format('public.halfvec(%s)', current_setting('PG_TEMP.REDUCED_DIM', TRUE))
        ELSE                                 format('vector(%s)',         current_setting('PG_TEMP.REDUCED_DIM', TRUE))
      END
    );
  END IF;

  /* ————————————————————————————————————————————————————————————
   * PCA / projection matrix storage
   * ————————————————————————————————————————————————————————————*/
  EXECUTE format($$
    CREATE TABLE IF NOT EXISTS reducing_matrix (
	row_idx  INT PRIMARY KEY,
	row_vec  vector(%s) NOT NULL       -- always FP32
    );
  $$, __vector_size);


  -- Helpful index for “give me everything > after_seq”
  CREATE INDEX IF NOT EXISTS posts_vectors_sync_seq_post_id_idx ON hivesense_app.posts_vectors(sync_seq, post_id);

  -- the current version of sqlfluff doesn't understand 'GRANT MAINTAIN'
  EXECUTE format( 'GRANT MAINTAIN ON ALL TABLES IN SCHEMA %s TO hived_group' , __schema_name );
  EXECUTE format( 'GRANT ALL ON SCHEMA %s TO hived_group' , __schema_name );

  END
$BODY$;

INSERT INTO hivesense_app_status
(
  id,
  continue_processing,
  parallel_workers,
  llm,
  ollama,
  start_block,
  embedding_batch_size,
  tokenizer_model,
  tokens_per_chunk,
  overlap_amount,
  use_halfvec_index,
  store_halfvec_embeddings,
  use_reduced_embeddings,
  reduced_dim,
  reduction_mode,
  hnsw_m,
  hnsw_ef_construction,
  default_ef_search,
  minimum_ann_candidates,
  allow_debugging,
  document_prefix,
  query_prefix,
  embedding_dimensionality,
  min_token_threshold,
  min_token_search_threshold,
  max_embeddings_per_post,
  desired_maintenance_work_mem_gb,
  advisory_lock_namespace_begin,
  max_visible_sync_seq,
  syncing_embeddings,
  sync_uuid
)
VALUES
(
    1,
    TRUE,
    current_setting('PG_TEMP.PARALLEL_WORKERS', TRUE)::INT,
    current_setting('PG_TEMP.LLM', TRUE)::TEXT,
    current_setting('PG_TEMP.OLLAMA_HOST', TRUE)::TEXT,
    current_setting('PG_TEMP.START_BLOCK', TRUE)::INT,
    current_setting('PG_TEMP.EMBEDDING_BATCH_SIZE', TRUE)::INT,
    current_setting('PG_TEMP.TOKENIZER_MODEL', TRUE)::TEXT,
    current_setting('PG_TEMP.TOKENS_PER_CHUNK', TRUE)::INT,
    current_setting('PG_TEMP.OVERLAP_AMOUNT', TRUE)::REAL,
    current_setting('PG_TEMP.USE_HALFVEC_INDEX', TRUE)::BOOLEAN,
    current_setting('PG_TEMP.STORE_HALFVEC_EMBEDDINGS', TRUE)::BOOLEAN,
    current_setting('PG_TEMP.USE_REDUCED_EMBEDDINGS', TRUE)::BOOLEAN,
    NULLIF(current_setting('PG_TEMP.REDUCED_DIM', TRUE)::INT,0),
    COALESCE(current_setting('PG_TEMP.REDUCTION_MODE', TRUE), 'none'),
    current_setting('PG_TEMP.HNSW_M', TRUE)::INT,
    current_setting('PG_TEMP.HNSW_EF_CONSTRUCTION', TRUE)::INT,
    current_setting('PG_TEMP.DEFAULT_EF_SEARCH', TRUE)::INT,
    current_setting('PG_TEMP.MINIMUM_ANN_CANDIDATES', TRUE)::INT,
    current_setting('PG_TEMP.ALLOW_DEBUGGING',   TRUE)::BOOLEAN,
    current_setting('PG_TEMP.DOCUMENT_PREFIX', TRUE)::TEXT,
    current_setting('PG_TEMP.QUERY_PREFIX', TRUE)::TEXT,
    current_setting('PG_TEMP.VECTOR_SIZE', TRUE)::INT,
    current_setting('PG_TEMP.MIN_TOKEN_THRESHOLD', TRUE)::INT,
    current_setting('PG_TEMP.MIN_TOKEN_SEARCH_THRESHOLD', TRUE)::INT,
    NULLIF(current_setting('PG_TEMP.MAX_EMBEDINGS_PER_POST', TRUE)::INT, 0),
    current_setting('PG_TEMP.MAINTENANCE_WORK_MEM', TRUE)::INT,
    10000, -- advisory_lock_namespace_begin
    0,     -- max_visible_sync_seq
    NULL,  -- syncing_embeddings
    NULL   -- sync_uuid
)
ON CONFLICT (id)
DO UPDATE SET
ollama = excluded.ollama,
embedding_batch_size = excluded.embedding_batch_size;
-- only ollama host and batch size can be overridden by subsequent install
-- changing llm model or number of host requires resync

CREATE SEQUENCE IF NOT EXISTS hivesense_app.batch_seq START 1;

CREATE TABLE IF NOT EXISTS hivesense_app.block_tasks (
  task_id     SERIAL PRIMARY KEY,
  batch_id    BIGINT   NOT NULL,
  shard       INT,          -- worker number (1…N), NULL if unclaimed
  first_block INT      NOT NULL,
  last_block  INT      NOT NULL,
  post_ids    INT[]    NOT NULL DEFAULT '{}',
  status      TEXT     NOT NULL DEFAULT 'pending',   -- pending | running | done
  claimed_at  TIMESTAMPTZ,
  finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS block_tasks_pending_idx ON hivesense_app.block_tasks (status, shard);

-- Table that records logical deletions
CREATE TABLE IF NOT EXISTS hivesense_app.deleted_embeddings (
    post_id  INT     NOT NULL REFERENCES hivesense_app.post_data (post_id),
    sync_seq INT     NOT NULL UNIQUE,
    PRIMARY KEY (post_id, sync_seq)
);

CREATE INDEX IF NOT EXISTS deleted_embeddings_sync_seq_post_id_idx ON hivesense_app.deleted_embeddings(sync_seq, post_id);

RESET ROLE;
